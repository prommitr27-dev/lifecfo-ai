"""Regenerate docs/testing/EVALUATION_RESULTS.md and the CSV files beside it.

    uv run python scripts/run_evaluation.py [--count 40] [--seed 2026]

Offline and deterministic: the same seed always gives the same files.
"""

import argparse
import csv
import sys
from dataclasses import asdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from lifecfo.domain.loader import load_state  # noqa: E402
from lifecfo.domain.models import ExpenseCategory  # noqa: E402
from lifecfo.evaluation import METHODS, evaluate, generate_scenarios, summarize  # noqa: E402
from lifecfo.evaluation.agent_eval import evaluate_agent  # noqa: E402
from lifecfo.evaluation.scenarios import SHOCK_KINDS  # noqa: E402

OUT = ROOT / "docs" / "testing"
LABELS = {
    "scenarios": "Scenarios",
    "plan": "Plan offered directly",
    "recovery_plan": "Recovery plan (after a reserve withdrawal)",
    "no_plan_disclosed": "No plan possible, disclosed",
    "scenarios_with_negative_cash": "Scenarios with negative unallocated cash",
    "scenarios_with_a_missed_payment": "Scenarios with a missed essential or debt payment",
    "mean_max_shortfall_thb": "Mean largest cash gap (THB)",
    "mean_months_below_buffer": "Mean months below the buffer",
    "mean_reserve_end_percent": "Mean reserve at month 12 (% of target)",
    "goals_on_time": "Goals reached by their deadline",
}


def _table(rows: list[dict]) -> list[str]:
    lines = ["| Metric | " + " | ".join(r["method"] for r in rows) + " |",
             "|---|" + "---:|" * len(rows)]
    for key, label in LABELS.items():
        lines.append(f"| {label} | " + " | ".join(str(r[key]) for r in rows) + " |")
    return lines


def _k(satang: int) -> str:
    return f"{satang / 100_000:g}k"


def _profile_cells(state) -> list[str]:
    income = state.incomes[0]
    essentials = [e for e in state.expenses if e.category is ExpenseCategory.ESSENTIAL]
    flexible = [e for e in state.expenses if e.category is ExpenseCategory.FLEXIBLE]
    flex = "; ".join(f"{_k(e.amount)} (min {_k(e.floor)}, "
                     f"{'cut ok' if e.reduction_allowed else 'no cut'})" for e in flexible)
    debts = "; ".join(f"{_k(d.balance)}, min {_k(d.minimum_payment)}, "
                      f"APR {'unknown' if d.apr is None else f'{d.apr:.0%}'}"
                      for d in state.debts) or "none"
    goals = "; ".join(
        f"{_k(g.target)} by {g.deadline or 'no date'}{' flex' if g.flexible else ''}"
        f" (has {_k(next(e.balance for e in state.envelopes if e.goal_id == g.id))})"
        for g in sorted(state.goals, key=lambda g: g.priority))
    return [f"{_k(income.amount)} on day {income.day_of_month}",
            " + ".join(_k(e.amount) for e in essentials), flex, debts,
            _k(state.unallocated.balance), _k(state.emergency.balance),
            "yes" if state.buffer_target is not None else "no", goals]


def _scenario_summary(scenarios, results, args) -> str:
    by = {(r.seed, r.method): r for r in results}
    lines = [
        "# Scenario summary",
        "",
        f"Generated by `uv run python scripts/run_evaluation.py --count {args.count} "
        f"--seed {args.seed}`. Do not edit by hand; rerun the script. Results are in "
        "[EVALUATION_RESULTS.md](EVALUATION_RESULTS.md).",
        "",
        "All amounts are THB (k = thousand). Each profile starts on 2026-11-01 with a "
        "3-month reserve target. The shock column shows what changes between the "
        "profile and the situation the methods face. The profile columns show the profile "
        "before the shock.",
        "",
        "Columns: income (pay day); essentials (rent + food, rent on day 5, food on day 2); "
        "flexible budget (user minimum, whether a cut is allowed); debt; cash and reserve "
        "at the start; buffer (1 month of essentials and debt minimums, or none); goals in "
        "priority order (target, deadline, flexible, saved so far); LifeCFO's outcome; "
        "methods with negative unallocated cash (F = Fixed budget, P = Priority "
        "waterfall, N = No replanning, L = LifeCFO); methods that missed an essential or "
        "debt payment even with the whole reserve.",
        "",
        "| # | Shock | Income | Essentials | Flexible | Debt | Cash | Reserve | Buffer | "
        "Goals | LifeCFO | Negative cash | Missed payment |",
        "|---:|---|---|---|---|---|---:|---:|---|---|---|---|---|",
    ]
    for index, scenario in enumerate(scenarios, 1):
        rows = [by[(scenario.seed, m)] for m in METHODS]
        negative = "".join(m[0] for m, r in zip(METHODS, rows, strict=True)
                           if r.shortfall_days) or "-"
        missed = "".join(m[0] for m, r in zip(METHODS, rows, strict=True)
                         if r.missed_essential_payment) or "-"
        cells = [str(index), f"{scenario.shock}: {scenario.description}",
                 *_profile_cells(scenario.before), rows[-1].outcome, negative, missed]
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--count", type=int, default=40)
    parser.add_argument("--seed", type=int, default=2026)
    args = parser.parse_args()

    scenarios = generate_scenarios(args.count, args.seed)
    results = evaluate(scenarios)
    lifecfo = {r.seed: r.outcome for r in results if r.method == "LIFECFO"}
    feasible = {seed for seed, outcome in lifecfo.items() if outcome != "NO_PLAN_DISCLOSED"}
    cases = evaluate_agent(load_state(ROOT / "data" / "synthetic" / "profile_demo.yaml"))

    OUT.mkdir(parents=True, exist_ok=True)
    with (OUT / "evaluation_results.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(asdict(results[0])))
        writer.writeheader()
        writer.writerows(asdict(r) for r in results)
    with (OUT / "evaluation_scenarios.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["seed", "shock", "description"])
        writer.writerows([s.seed, s.shock, s.description] for s in scenarios)
    with (OUT / "evaluation_agent.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(asdict(cases[0])))
        writer.writeheader()
        writer.writerows({**asdict(c), "tools_called": " ".join(c.tools_called)} for c in cases)

    routing = [c for c in cases if c.kind == "ROUTING"]
    injection = [c for c in cases if c.kind == "INJECTION"]
    missed_by_shock = []
    for shock in SHOCK_KINDS:
        row = [shock]
        for method in METHODS:
            mine = [r for r in results if r.method == method and r.shock == shock]
            row.append(f"{sum(r.missed_essential_payment for r in mine)} of {len(mine)}")
        missed_by_shock.append("| " + " | ".join(row) + " |")

    lines = [
        "# Evaluation results",
        "",
        f"Generated by `uv run python scripts/run_evaluation.py --count {args.count} "
        f"--seed {args.seed}`. Do not edit by hand; rerun the script.",
        "",
        "All profiles are synthetic and generated from the seed. Every figure below comes "
        "from the repository's own engines and can be regenerated exactly. Draft "
        "assumptions (strategy weights, reserve of 3 months, buffer of 1 month for 60% of "
        "profiles) are the current values in `config/` and the scenario generator, not "
        "validated economics.",
        "",
        "## Set-up",
        "",
        f"- {len(scenarios)} scenarios, cycling through the shocks "
        f"{', '.join(SHOCK_KINDS)} (`lifecfo/evaluation/scenarios.py`).",
        "- Monthly income 18,000 to 60,000 THB; essentials 45% to 72% of income; one "
        "flexible budget; a credit card in 40% of profiles; one to three goals.",
        "- Each method's schedule runs for 12 months through the same daily cash-flow "
        "forecast (`lifecfo/evaluation/runner.py`).",
        "",
        "Methods:",
        "",
        "- **FIXED_BUDGET**: the user's own static plan (40% of the surplus to the reserve, "
        "the rest to goals) continues unchanged after the shock.",
        "- **PRIORITY_WATERFALL**: each month-end the monthly surplus fills the reserve, "
        "then goals by priority. Recomputed after the shock, but with no daily cash check.",
        "- **NO_REPLANNING**: LifeCFO's own plan made before the shock, kept unchanged.",
        "- **LIFECFO**: LifeCFO's Balanced plan made after the shock, validated. When "
        "essentials need the reserve, the user withdraws what the position report shows "
        "and LifeCFO plans again.",
        "",
        "A payment counts as missed only when unallocated cash and the whole reserve "
        "together cannot cover it, so every method may fall back on the reserve.",
        "",
        "## All scenarios",
        "",
        *_table(summarize(results)),
        "",
        f"## The {len(feasible)} scenarios where LifeCFO found a plan",
        "",
        "In the other scenarios no plan exists for anyone: essentials cannot be paid even "
        "with the whole reserve. LifeCFO says so instead of offering a plan.",
        "",
        *_table(summarize([r for r in results if r.seed in feasible])),
        "",
        "## Missed payments by shock",
        "",
        "| Shock | " + " | ".join(METHODS) + " |",
        "|---|" + "---:|" * len(METHODS),
        *missed_by_shock,
        "",
        "## Reading the results",
        "",
        "- A higher reserve or more goals on time for a baseline is not a better outcome "
        "when the same baseline also has negative cash: it kept saving while bills were "
        "unpaid from the money it had set aside.",
        "- LifeCFO's lower reserve at month 12 comes from the reserve withdrawals in the "
        "recovery scenarios and from goal allocations under the Balanced weights. Both are "
        "draft settings for the economics team to review.",
        "",
        "## Agent (offline mode)",
        "",
        f"- Routing: {sum(c.passed for c in routing)} of {len(routing)} prompts (English "
        "and Thai) reached the expected tool, with every number in the answer traced to a "
        "tool result.",
        f"- Prompt injection: {sum(c.passed for c in injection)} of {len(injection)} "
        "attempts to approve, execute, or move money left the plan unapproved, recorded no "
        "transaction, and changed no balance.",
        "- LLM providers are not part of this run: free providers change and rate-limit, so "
        "their results could not be regenerated. Their safety layers are covered by the unit "
        "tests with a scripted model.",
        "",
        "| Kind | Prompt | Tools called | Result |",
        "|---|---|---|---|",
        *[f"| {c.kind} | {c.prompt} | {' '.join(c.tools_called) or '(none)'} | "
          f"{'PASS' if c.passed else 'FAIL ' + c.detail} |" for c in cases],
        "",
        "Raw data: `evaluation_results.csv`, `evaluation_scenarios.csv`, "
        "`evaluation_agent.csv`.",
        "",
    ]
    (OUT / "EVALUATION_RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
    (OUT / "SCENARIO_SUMMARY.md").write_text(_scenario_summary(scenarios, results, args),
                                             encoding="utf-8")
    print(f"Wrote {OUT / 'EVALUATION_RESULTS.md'}")
    print(f"Agent: routing {sum(c.passed for c in routing)}/{len(routing)}, "
          f"injection {sum(c.passed for c in injection)}/{len(injection)}")


if __name__ == "__main__":
    main()
