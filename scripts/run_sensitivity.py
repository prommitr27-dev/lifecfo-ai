"""Balanced strategy weight sensitivity across several seeds (Member 2 review).

Runs scripts/run_evaluation.py once per seed and variant with only the listed
BALANCED parameters changed, then writes a per-seed summary CSV and a Markdown
report to docs/testing/sensitivity/. The strategy config and the canonical
evaluation files in docs/testing/ are restored byte for byte afterwards.

    uv run python scripts/run_sensitivity.py
"""

import csv
import statistics
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "config" / "strategy_weights.yaml"
EVAL_DIR = ROOT / "docs" / "testing"
OUT = EVAL_DIR / "sensitivity"
SEEDS = [2026, 2027, 2028, 2029, 2030]
COUNT = 40
VARIANTS = {
    "BASELINE": {},
    "RESERVE_WEIGHT_10": {"reserve_weight": 10},
    "GOAL_WEIGHT_8": {"goal_weight": 8},
    "RESERVE_RAMP_3": {"reserve_ramp_months": 3},
    "COMBINED_RESERVE10_GOAL8_RAMP3": {
        "reserve_weight": 10,
        "goal_weight": 8,
        "reserve_ramp_months": 3,
    },
}


def metrics(rows: list[dict]) -> dict:
    due = sum(int(r["goals_due"]) for r in rows)
    on_time = sum(int(r["goals_on_time"]) for r in rows)

    def mean(key: str, digits: int) -> float:
        return round(statistics.mean(float(r[key]) for r in rows), digits) if rows else 0

    return {
        "scenario_count": len(rows),
        "no_plan": sum(r["outcome"] == "NO_PLAN_DISCLOSED" for r in rows),
        "negative_cash_scenarios": sum(int(r["shortfall_days"]) > 0 for r in rows),
        "missed_payment_scenarios": sum(
            r["missed_essential_payment"].lower() == "true" for r in rows
        ),
        "mean_largest_cash_gap_thb": round(mean("max_shortfall", 1)),
        "mean_months_below_buffer": mean("months_below_buffer", 2),
        "mean_reserve_end_percent": mean("reserve_end_percent", 1),
        "goals_on_time_count": on_time,
        "goals_due": due,
        "goals_on_time_rate_percent": round(100 * on_time / due, 1) if due else 0,
    }


def summarize(rows: list[dict]) -> tuple[dict, dict]:
    life = [r for r in rows if r["method"] == "LIFECFO"]
    feasible = [r for r in life if r["outcome"] != "NO_PLAN_DISCLOSED"]
    return metrics(life), metrics(feasible)


def goals(m: dict) -> str:
    return f"{m['goals_on_time_count']}/{m['goals_due']} ({m['goals_on_time_rate_percent']}%)"


def run() -> tuple[list[dict], list[dict], dict]:
    base_text = CONFIG.read_text(encoding="utf-8")
    base = yaml.safe_load(base_text)
    saved = {p: p.read_bytes() for p in EVAL_DIR.iterdir() if p.is_file()}
    all_rows: list[dict] = []
    summary: list[dict] = []
    try:
        for seed in SEEDS:
            for name, changes in VARIANTS.items():
                cfg = yaml.safe_load(base_text)
                cfg["strategies"]["BALANCED"].update(changes)
                CONFIG.write_text(yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
                subprocess.run(
                    [sys.executable, "scripts/run_evaluation.py", "--count", str(COUNT),
                     "--seed", str(seed)],
                    cwd=ROOT, check=True, capture_output=True, text=True,
                )
                with (EVAL_DIR / "evaluation_results.csv").open(encoding="utf-8") as handle:
                    rows = list(csv.DictReader(handle))
                for r in rows:
                    r["experiment_seed"], r["variant"] = seed, name
                all_rows.extend(rows)
                all_m, feas_m = summarize(rows)
                balanced = cfg["strategies"]["BALANCED"]
                summary.append({
                    "seed": seed,
                    "variant": name,
                    **{f"all_{k}": v for k, v in all_m.items()},
                    **{f"feasible_{k}": v for k, v in feas_m.items()},
                    "reserve_weight": balanced["reserve_weight"],
                    "goal_weight": balanced["goal_weight"],
                    "reserve_ramp_months": balanced["reserve_ramp_months"],
                })
                print(seed, name, "goals", goals(all_m))
    finally:
        CONFIG.write_text(base_text, encoding="utf-8")
        for path, data in saved.items():
            path.write_bytes(data)
    return all_rows, summary, base


def write_report(all_rows: list[dict], summary: list[dict], base: dict) -> None:
    OUT.mkdir(exist_ok=True)
    with (OUT / "seed_summary.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(summary[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(summary)

    lines = [
        "# Balanced strategy weight sensitivity (multi-seed)",
        "",
        "Generated by `uv run python scripts/run_sensitivity.py`. Do not edit by hand.",
        "",
        f"{len(SEEDS)} seeds ({', '.join(map(str, SEEDS))}), {COUNT} synthetic scenarios per "
        f"seed, {len(VARIANTS)} variants: {len(SEEDS) * len(VARIANTS)} evaluation runs. Only "
        "the listed BALANCED parameters change. \"Feasible\" excludes `NO_PLAN_DISCLOSED` "
        "cases. Goal completion is goals on time divided by goals due. Synthetic stress "
        "test, not calibration.",
        "",
        "## Pooled results by variant",
        "",
        "| Variant | Reserve weight | Goal weight | Ramp months | Scenarios | No plan | "
        "Negative cash | Missed payment | Mean largest gap (THB) | Months below buffer | "
        "Reserve end (%) | Goals on time | Feasible scenarios | Feasible missed payment | "
        "Feasible reserve end (%) | Feasible goals on time |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|---:|---:|---|",
    ]
    for name, changes in VARIANTS.items():
        all_m, feas_m = summarize([r for r in all_rows if r["variant"] == name])
        cfg = {**base["strategies"]["BALANCED"], **changes}
        values = [
            name, cfg["reserve_weight"], cfg["goal_weight"], cfg["reserve_ramp_months"],
            all_m["scenario_count"], all_m["no_plan"], all_m["negative_cash_scenarios"],
            all_m["missed_payment_scenarios"], all_m["mean_largest_cash_gap_thb"],
            all_m["mean_months_below_buffer"], all_m["mean_reserve_end_percent"], goals(all_m),
            feas_m["scenario_count"], feas_m["missed_payment_scenarios"],
            feas_m["mean_reserve_end_percent"], goals(feas_m),
        ]
        lines.append("| " + " | ".join(map(str, values)) + " |")
    lines += [
        "",
        "## Seed-by-seed goal completion",
        "",
        "| Seed | Variant | All goals on time | Feasible goals on time | No-plan scenarios |",
        "|---:|---|---:|---:|---:|",
    ]
    for r in summary:
        lines.append(
            f"| {r['seed']} | {r['variant']} | {r['all_goals_on_time_count']}/"
            f"{r['all_goals_due']} ({r['all_goals_on_time_rate_percent']}%) | "
            f"{r['feasible_goals_on_time_count']}/{r['feasible_goals_due']} "
            f"({r['feasible_goals_on_time_rate_percent']}%) | {r['all_no_plan']} |"
        )
    life = [r for r in all_rows if r["method"] == "LIFECFO"]
    no_plan = [r for r in life if r["outcome"] == "NO_PLAN_DISCLOSED"]
    negative = [r for r in life if int(r["shortfall_days"]) > 0]
    missed = [r for r in life if r["missed_essential_payment"].lower() == "true"]
    no_plan_sets = {
        frozenset((r["experiment_seed"], r["seed"]) for r in no_plan if r["variant"] == name)
        for name in VARIANTS
    }
    lines += [
        "",
        "## Safety check (row level, all seeds and variants)",
        "",
        f"- LifeCFO rows: {len(life)} ({len(SEEDS)} seeds x {COUNT} scenarios x "
        f"{len(VARIANTS)} variants).",
        f"- Negative-cash rows inside `NO_PLAN_DISCLOSED`: "
        f"{sum(r['outcome'] == 'NO_PLAN_DISCLOSED' for r in negative)} of {len(negative)}.",
        f"- Missed-payment rows inside `NO_PLAN_DISCLOSED`: "
        f"{sum(r['outcome'] == 'NO_PLAN_DISCLOSED' for r in missed)} of {len(missed)}.",
        f"- Every variant has the same set of no-plan scenarios: "
        f"{'yes' if len(no_plan_sets) == 1 else 'no'}.",
        "",
        "## Reading the results",
        "",
        "- When the safety check shows every negative-cash and missed-payment row inside "
        "`NO_PLAN_DISCLOSED` and the same no-plan set in every variant, those counts cannot "
        "change with the Balanced weights.",
        "- Compare variants seed by seed, not only pooled totals.",
        "- Interpretation and recommendation: "
        "[MEMBER2_FINANCE_REVIEW.md](../MEMBER2_FINANCE_REVIEW.md).",
        "",
    ]
    (OUT / "SENSITIVITY_RESULTS.md").write_text("\n".join(lines), encoding="utf-8")
    print("Wrote", OUT / "seed_summary.csv", OUT / "SENSITIVITY_RESULTS.md")


if __name__ == "__main__":
    write_report(*run())
